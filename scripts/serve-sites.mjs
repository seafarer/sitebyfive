#!/usr/bin/env node
/**
 * Runs the production Worker locally over dist/sites/ (build with `npm run build:sites` first).
 * Open http://<site>.localhost:8787/. wrangler dev rewrites the host to the route's zone, so this
 * runs from a copy of wrangler.jsonc without the route.
 */
import { spawn } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { root } from "./sites.mjs";

const config = readFileSync(`${root}wrangler.jsonc`, "utf8").replace(/^\s*"routes":\s*\[[\s\S]*?\],\n/m, "");
writeFileSync(`${root}wrangler.local.jsonc`, `// Generated by scripts/serve-sites.mjs. Do not edit.\n${config}`);
spawn("npx", ["wrangler", "dev", "-c", "wrangler.local.jsonc", ...process.argv.slice(2)], { cwd: root, stdio: "inherit" });
