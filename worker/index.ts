/**
 * Cloudflare Worker for every site on *.<baseDomain> (one deploy, routed by hostname).
 *
 * Static files: `npm run build:sites` builds each non-draft site into dist/sites/<slug>/ and writes
 * worker/sites.generated.json (hostname → site). Requests are served from that site's folder;
 * anything unknown is a 404. Preview sites get `X-Robots-Tag: noindex`.
 *
 * POST /api/contact: emails the submission through Cloudflare Email Service (send_email binding)
 * to the site's `formsTo` (or CONTACT_TO), from CONTACT_FROM with the site name as sender name,
 * then 303-redirects to the form's `_redirect` (same origin only), whose #…-sent hash reveals the
 * success message via CSS :target. With `Accept: application/json` (the in-page script in
 * Contact.astro) it answers `{ ok, error? }` instead, so the page never reloads.
 *
 * Every destination address must be verified in Email Routing (free on every plan). CONTACT_FROM
 * must be on a domain with Email Routing enabled in the same Cloudflare account.
 */

import manifest from "./sites.generated.json";

interface EmailAddress {
  email: string;
  name?: string;
}
interface SendEmail {
  send(message: {
    to: string | EmailAddress | (string | EmailAddress)[];
    from: string | EmailAddress;
    subject: string;
    text?: string;
    html?: string;
    replyTo?: string | EmailAddress;
  }): Promise<{ messageId: string }>;
}
interface Env {
  ASSETS: { fetch(request: Request): Promise<Response> };
  EMAIL: SendEmail;
  /** Studio inbox: receives submissions for sites without `formsTo`. Must be verified. */
  CONTACT_TO: string;
  /** Sender on an Email Routing domain, e.g. "forms@sitebyfive.com". */
  CONTACT_FROM: string;
}

/** One entry per deployed site, generated by scripts/build-sites.mjs. */
interface SiteEntry {
  slug: string;
  name: string;
  status: "preview" | "live";
  hosts: string[];
  /** Old path → new path or URL (site.yaml `redirects`). */
  redirects?: Record<string, string>;
  formsTo?: string;
}

const { sites, redirects } = manifest as { sites: SiteEntry[]; redirects: Record<string, string> };
const byHost = new Map(sites.flatMap((site) => site.hosts.map((host) => [host, site] as const)));

const MAX_BODY = 128 * 1024; // questionnaires post a dozen long answers
const MAX_FIELD = 8000;
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

function page(status: number, title: string, body: string, back?: string): Response {
  const html = `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>${title}</title>
<body style="font:17px/1.6 system-ui,sans-serif;max-width:36rem;margin:15vh auto;padding:0 1.5rem;color:#222">
<h1 style="font-size:1.6rem">${title}</h1><p>${body}</p>${back ? `<p><a href="${back}">Go back</a></p>` : ""}</body></html>`;
  return new Response(html, { status, headers: { "content-type": "text/html; charset=utf-8" } });
}

/** Only redirect back to this site. */
function safeRedirect(value: FormDataEntryValue | null, origin: string, fallback: string): string {
  if (typeof value !== "string") return fallback;
  try {
    const url = new URL(value, origin);
    return url.origin === origin ? url.toString() : fallback;
  } catch {
    return fallback;
  }
}

async function handleContact(request: Request, env: Env, site: SiteEntry): Promise<Response> {
  const url = new URL(request.url);
  const origin = url.origin;
  const referer = request.headers.get("referer") ?? `${origin}/`;
  // The in-page script asks for JSON; a plain form post gets HTML pages and redirects.
  const wantsJson = (request.headers.get("accept") ?? "").includes("application/json");
  const fail = (status: number, title: string, body: string, back?: string) =>
    wantsJson ? Response.json({ ok: false, error: body }, { status }) : page(status, title, body, back);
  const done = (redirect: string) => (wantsJson ? Response.json({ ok: true }) : Response.redirect(redirect, 303));

  const declared = Number(request.headers.get("content-length") ?? 0);
  if (declared > MAX_BODY) return fail(413, "That message is too long", "Please shorten it and try again.", referer);

  const sentFrom = request.headers.get("origin");
  if (sentFrom && sentFrom !== origin) return fail(403, "Not allowed", "This form can only be sent from its own website.");

  let form: FormData;
  try {
    form = await request.formData();
  } catch {
    return fail(400, "Something went wrong", "We couldn't read the form. Please try again.", referer);
  }

  const redirect = safeRedirect(form.get("_redirect"), origin, referer);

  // Honeypot: bots fill every field. Pretend it worked.
  if (String(form.get("_gotcha") ?? "").trim() !== "") return done(redirect);

  const fields: [string, string][] = [];
  for (const [key, value] of form.entries()) {
    if (key.startsWith("_") || typeof value !== "string") continue;
    fields.push([key, value.slice(0, MAX_FIELD).trim()]);
  }
  if (fields.every(([, v]) => v === "")) return fail(400, "The form was empty", "Please fill it in and try again.", referer);

  const replyTo = fields.find(([k, v]) => /email/i.test(k) && EMAIL_RE.test(v))?.[1];
  const subject = String(form.get("_subject") ?? "Website enquiry").slice(0, 200);
  const pageUrl = redirect.split("#")[0];
  const text = [...fields.map(([k, v]) => `${k}:\n${v || "—"}\n`), `Sent from ${pageUrl}`].join("\n");

  try {
    await env.EMAIL.send({
      to: site.formsTo ?? env.CONTACT_TO,
      from: { email: env.CONTACT_FROM, name: `${site.name} website` },
      subject,
      text,
      ...(replyTo ? { replyTo } : {}),
    });
  } catch (err) {
    const code = (err as { code?: string }).code ?? "unknown";
    console.error("contact send failed", code, (err as Error).message);
    return fail(502, "Your message wasn't sent", "Something went wrong on our end. Please try again in a few minutes, or contact us directly.", referer);
  }

  return done(redirect);
}

/** Serve a file from this site's folder, keeping redirects and 404s inside the site. */
async function serveAsset(request: Request, env: Env, site: SiteEntry): Promise<Response> {
  const url = new URL(request.url);
  const prefix = `/${site.slug}`;
  let res = await env.ASSETS.fetch(new Request(new URL(`${prefix}${url.pathname}${url.search}`, url), request));
  if (res.status === 404) {
    const notFound = await env.ASSETS.fetch(new Request(new URL(`${prefix}/404.html`, url)));
    res = new Response(notFound.ok ? notFound.body : "Not found", { status: 404, headers: notFound.ok ? notFound.headers : {} });
  }
  // Trailing-slash redirects come back with the site prefix; strip it.
  const location = res.headers.get("location");
  if (location?.startsWith(`${prefix}/`)) {
    res = new Response(res.body, res);
    res.headers.set("location", location.slice(prefix.length));
  }
  if (site.status !== "live") {
    res = new Response(res.body, res);
    res.headers.set("x-robots-tag", "noindex, nofollow");
  }
  return res;
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);
    const { pathname, hostname } = url;
    // Bare domain → www (e.g. sitebyfive.com → www.sitebyfive.com); retired sites → one full URL.
    const canonical = redirects[hostname];
    if (canonical?.startsWith("https://")) return Response.redirect(canonical, 301);
    if (canonical) return Response.redirect(`https://${canonical}${pathname}${url.search}`, 301);
    const site = byHost.get(hostname);
    if (!site) return new Response(`No site at ${hostname}`, { status: 404, headers: { "content-type": "text/plain" } });
    const moved = site.redirects?.[pathname.replace(/(.)\/$/, "$1")];
    if (moved) return Response.redirect(new URL(moved, url).toString(), 301);
    if (pathname === "/api/contact") {
      if (request.method !== "POST") return new Response("Method not allowed", { status: 405, headers: { allow: "POST" } });
      return handleContact(request, env, site);
    }
    return serveAsset(request, env, site);
  },
};
